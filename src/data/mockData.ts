export function getPurchaseTotal(rows: PurchaseRow[]) {
  return rows.reduce((sum, row) => sum + getRowAmount(row), 0)
}

export function getRowAmount(row: PurchaseRow) {
  return row.amountOverride ?? row.quantity * row.price
}

export function getRowVatRate(row: PurchaseRow) {
  if (typeof row.vatRate === 'number') {
    return row.vatRate
  }

  if (row.price <= 0) {
    return 0
  }

  const reducedVatCategories = new Set(['Перчатки', 'Маски', 'Шприцы', 'Иглы', 'Салфетки', 'Бахилы'])
  return reducedVatCategories.has(row.category) ? 10 : 22
}

export function getRowVatAmount(row: PurchaseRow) {
  const rate = getRowVatRate(row)
  const amount = getRowAmount(row)

  if (rate <= 0 || amount <= 0) {
    return 0
  }

  return amount * (rate / (100 + rate))
}

export function getRowAmountWithoutVat(row: PurchaseRow) {
  return getRowAmount(row) - getRowVatAmount(row)
}

export function getReviewCount(rows: PurchaseRow[]) {
  return rows.filter((row) => row.tone !== 'ready').length
}

export function getDocuments(rows: PurchaseRow[]): GeneratedDocument[] {
  const supplierDocuments = Array.from(
    rows.reduce((map, row) => {
      const current = map.get(row.supplier) ?? { rowCount: 0, total: 0 }
      current.rowCount += 1
      current.total += getRowAmount(row)
      map.set(row.supplier, current)
      return map
    }, new Map<string, { rowCount: number; total: number }>()),
  ).map(([supplier, value], index) => ({
    id: `supplier-${index + 1}`,
    title: `Заказ поставщику ${index + 1}.xlsx`,
    subtitle: supplier,
    supplier,
    rowCount: value.rowCount,
    total: value.total,
  }))

  return [
    {
      id: 'final-table',
      title: 'Итоговая закупочная таблица.xlsx',
      subtitle: demoCycleTitle,
      rowCount: rows.length,
      total: getPurchaseTotal(rows),
    },
    ...supplierDocuments,
  ]
}

