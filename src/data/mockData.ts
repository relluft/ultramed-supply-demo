function demoPriceForExtraCatalogItem(id: string, category: string) {
  if (id.includes('primer')) return 2860
  if (id.includes('wax')) return 1240
  if (id.includes('archwires') || id.includes('niti')) return 3920
  if (id.includes('elastics') || id.includes('ligatures') || id.includes('chain')) return 980
  if (id.includes('hooks')) return 1760

  const categoryPrice: Record<string, number> = {
    Анестезия: 1680,
    Гигиена: 920,
    Дезинфекция: 1460,
    Изоляция: 1320,
    Ортодонтия: 2140,
    Ортопедия: 2480,
    Расходники: 760,
    Терапия: 1180,
    Хирургия: 1820,
  }

  return categoryPrice[category] ?? 990
}

function extraCatalogItem(
  id: string,
  fullName: string,
  shortName: string,
  category: string,
  unit: string,
  packageLabel: string,
  searchSynonyms: string[],
  minStock = 2,
  desiredStock = 8,
  primarySupplierId = 'sup-stommarket',
): CatalogItem {
  return {
    id,
    fullName,
    shortName,
    category,
    unit,
    packageLabel,
    orderMultiple: 1,
    minStock,
    desiredStock,
    primarySupplierId,
    alternativeSupplierIds: primarySupplierId === 'sup-stommarket' ? ['sup-dentalpost'] : ['sup-stommarket'],
    price: demoPriceForExtraCatalogItem(id, category),
    searchSynonyms,
    requiresApprovalForReplacement: false,
    active: true,
  }
}

